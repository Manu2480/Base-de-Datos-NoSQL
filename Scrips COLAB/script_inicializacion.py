def ask_connection_uri() -> str:
    uri = os.getenv("MONGODB_URI")
    if uri:
        return uri
    return getpass.getpass(
        "Pegue MONGODB_URI (la entrada no se mostrará y no se guardará): "
    ).strip()


def create_or_update_collections(database: Any) -> None:
    existing = set(database.list_collection_names())
    for name in COLLECTIONS:
        if name not in existing:
            options: dict[str, Any] = {}
            if name in COLLECTION_VALIDATORS:
                options = {
                    "validator": COLLECTION_VALIDATORS[name],
                    "validationLevel": "strict",
                    "validationAction": "error",
                }
            database.create_collection(name, **options)
            print(f"[CREADA] {name}")
        elif name in COLLECTION_VALIDATORS:
            database.command(
                {
                    "collMod": name,
                    "validator": COLLECTION_VALIDATORS[name],
                    "validationLevel": "strict",
                    "validationAction": "error",
                }
            )
            print(f"[ACTUALIZADA] validador de {name}")
        else:
            print(f"[EXISTENTE] {name}")


