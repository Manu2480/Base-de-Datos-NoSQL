function mapa(lista, clave) {
  const m = {};
  lista.forEach((x) => { m[x[clave]] = x; });
  return m;
}
function ref(m, nombre, tipo) {
  if (!m[nombre]) throw new Error(`${tipo} no encontrado: "${nombre}"`);
  return m[nombre]._id;
}

const sintomasDocs = SINTOMAS.map(([nombre, descripcion]) => ({ _id: new ObjectId(), nombre, descripcion }));
const S_ = mapa(sintomasDocs, 'nombre');

const dxDocs = DIAGNOSTICOS.map(([nombre, categoria, descripcion, manifestaciones_visuales, sint]) => ({
  _id: new ObjectId(), nombre, categoria, descripcion, manifestaciones_visuales,
  sintomas_ids: sint.map((s) => ref(S_, s, 'Síntoma')),
  tratamientos_ids: [],
}));
const DX_ = mapa(dxDocs, 'nombre');

const medDocs = MEDICAMENTOS.map((m) => ({
  _id: new ObjectId(), nombre: m.nombre, principio_activo: m.principio_activo,
  indicaciones: m.indicaciones, contraindicaciones: m.contraindicaciones, _inter: m.interacciones || [],
}));
const MED_ = mapa(medDocs, 'nombre');
medDocs.forEach((m) => {
  m.interacciones = m._inter.map(([n, descripcion]) => ({ medicamento_relacionado_id: ref(MED_, n, 'Medicamento'), descripcion }));
  delete m._inter;
});

const tratDocs = TRATAMIENTOS.map((t) => ({
  _id: new ObjectId(), nombre: t.nombre, descripcion: t.descripcion,
  diagnosticos_ids: t.diagnosticos.map((d) => ref(DX_, d, 'Diagnóstico')),
  indicaciones: t.indicaciones, precauciones: t.precauciones,
  medicamentos: t.medicamentos.map(([n, pautas]) => ({
    medicamento_id: ref(MED_, n, 'Medicamento'),
    pautas_generales: pautas.map(([grupo_poblacional, cantidad, frecuencia]) => ({ grupo_poblacional, cantidad, frecuencia })),
  })),
}));
// referencia inversa diagnóstico -> tratamientos
tratDocs.forEach((t) => t.diagnosticos_ids.forEach((id) => {
  dxDocs.find((d) => d._id.equals(id)).tratamientos_ids.push(t._id);
}));

db.sintomas.insertMany(sintomasDocs);
db.diagnosticos_dermatologicos.insertMany(dxDocs);
db.medicamentos.insertMany(medDocs);
db.tratamientos.insertMany(tratDocs);

print(`✔ Catálogo: ${sintomasDocs.length} síntomas, ${dxDocs.length} diagnósticos, ${medDocs.length} medicamentos, ${tratDocs.length} tratamientos`);
